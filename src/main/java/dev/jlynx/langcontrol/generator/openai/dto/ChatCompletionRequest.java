package dev.jlynx.langcontrol.generator.openai.dto;

import com.fasterxml.jackson.annotation.JsonProperty;
import lombok.Builder;

import java.util.List;

/**
 * Represents a request to generate a chat completion using a specified model and input messages.
 * This class is designed to be used with OpenAI's chat-based models for conversational AI.
 * <p>
 * The {@code ChatCompletionRequest} encapsulates the required input data for generating a response,
 * such as the chosen model, the conversation's message history, and configuration parameters
 * like the maximum output token limit, number of completions to generate, and sampling temperature.
 * </p>
 *
 * <ul>
 *   <li>{@code model}: The name of the model to use for generating the response. This defines the behaviour
 *   and capability of the resulting chat completion.</li>
 *   <li>{@code messages}: A list of {@link ChatMessage} instances representing the exchange of chat inputs
 *   and outputs within the session. These messages provide the conversational context for completing the user's
 *   request.</li>
 *   <li>{@code maxCompletionTokens}: Specifies the maximum number of tokens to generate in the completion. This
 *   limits the length of the resulting output.</li>
 *   <li>{@code n}: Indicates the number of completions to generate for the input messages. Generates multiple
 *   responses when specified.</li>
 *   <li>{@code temperature}: A floating-point value that controls the randomness of the response. Higher values
 *   result in more diverse outputs, while lower values make the output deterministic.</li>
 * </ul>
 *
 * <p>
 * Additionally, a nested {@code ChatMessage} record is provided to structure the individual pieces of a chat
 * interaction by combining a {@link ChatMessageRole} and content.
 * </p>
 *
 * <p>
 * For generating chat completions, this request class is commonly paired with a corresponding response class
 * such as {@link ChatCompletionResponse}.
 * </p>
 */
@Builder
public record ChatCompletionRequest(
        String model,
        List<ChatMessage> messages,
        @JsonProperty("max_completion_tokens")
        Integer maxCompletionTokens,
        Integer n,
        Double temperature
) {

    /**
     * Represents an individual message within a chat-based interaction.
     * <p>
     * A {@code ChatMessage} encapsulates the role of the message sender and the
     * content of the message itself. It is utilised to provide structured input
     * for conversational AI models, enabling a coherent exchange of inputs and outputs.
     * </p>
     *
     * <ul>
     *   <li>{@code role}: The role of the message sender, defined by {@link ChatMessageRole}.
     *   This could indicate whether the message is generated by the system, a user, or the assistant.</li>
     *   <li>{@code content}: The textual content of the message, representing either a user query,
     *   an assistant response, or other forms of communication.</li>
     * </ul>
     *
     * <p>
     * This record is commonly used within the {@link ChatCompletionRequest} to establish the
     * context of the conversation by providing the model with a sequence of prior exchanges.
     * In return, the model generates a completion that continues or responds to the provided messages.
     * </p>
     */
    public record ChatMessage(
            ChatMessageRole role,
            String content
    ) {
    }
}
